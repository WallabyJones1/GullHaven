"""Build Gullhaven: concatenates src/js/m*.js into src/template.html.
Outputs: public/index.html (served by server.js), game.html (the single-file artifact) and shared.js (the rules the server runs)."""
import glob, os, re, sys
ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, 'src')
SHARED = ['m00_util', 'm00a_config', 'm01_collection', 'm04_items', 'm04c_csim', 'm04d_catalog', 'm04e_env', 'm04f_machine']

def asc(s):
    return ''.join(c if ord(c) < 128 else ('\\u%04x' % ord(c) if ord(c) < 0x10000 else ''.join('\\u%04x' % u for u in (0xD800 + ((ord(c) - 0x10000) >> 10), 0xDC00 + ((ord(c) - 0x10000) & 0x3FF)))) for c in s)

def html_asc(s):
    return ''.join(c if ord(c) < 128 else '&#%d;' % ord(c) for c in s)

mods = sorted(glob.glob(os.path.join(SRC, 'js', 'm*.js')))
js = "\n'use strict';\n" + '\n'.join(open(m, encoding='utf8').read() for m in mods)
js = asc(js)
if '</script' in js.lower():
    sys.exit('module contains </script')
tpl = open(os.path.join(SRC, 'template.html'), encoding='utf8').read()
fonts = open(os.path.join(SRC, 'fonts.css'), encoding='utf8').read()
tpl = html_asc(tpl)
out = tpl.replace('/*@@FONTS@@*/', fonts).replace('/*@@JS@@*/', js)
assert '@@' not in out.replace('@@JS@@', ''), 'placeholder left'
assert all(ord(c) < 128 for c in out), 'non-ascii in output'
open(os.path.join(ROOT, 'game.html'), 'w', encoding='ascii').write(out)
os.makedirs(os.path.join(ROOT, 'public'), exist_ok=True)
page = '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover,user-scalable=no"><meta name="apple-mobile-web-app-capable" content="yes"><meta name="theme-color" content="#14223a"></head><body>\n' + out + '\n</body></html>'
open(os.path.join(ROOT, 'public', 'index.html'), 'w', encoding='ascii').write(page)
shared = '/* generated by build.py from ' + ', '.join(SHARED) + ' */\n' + asc('\n'.join(open(os.path.join(SRC, 'js', m + '.js'), encoding='utf8').read() for m in SHARED))
open(os.path.join(ROOT, 'shared.js'), 'w', encoding='ascii').write(shared)
print('built', len(mods), 'modules,', len(out) // 1024, 'KB')
